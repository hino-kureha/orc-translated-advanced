def get_font(size):
    try:
        if FONT_PATH and os.path.exists(FONT_PATH):
            return ImageFont.truetype(FONT_PATH, size)
    except Exception:
        pass
    try:
        return ImageFont.truetype("DejaVuSans-Bold.ttf", size)
    except Exception:
        return ImageFont.load_default()

def wrap_text(draw, text, font, max_w):
    words = text.split()
    if not words:
        return [""]
    lines, cur = [], words[0]
    for w in words[1:]:
        test = f"{cur} {w}"
        if draw.textbbox((0, 0), test, font=font)[2] <= max_w:
            cur = test
        else:
            lines.append(cur)
            cur = w
    lines.append(cur)
    return lines

def escribir_texto(img_pil, texto, x1, y1, x2, y2):
    draw = ImageDraw.Draw(img_pil)
    bw, bh = x2 - x1, y2 - y1
    pad_x, pad_y = int(bw * 0.08), int(bh * 0.10)
    aw, ah = max(40, bw - 2 * pad_x), max(30, bh - 2 * pad_y)

    best_size, best_lines = None, []
    for size in range(min(60, int(ah * 0.6)), 12, -2):
        font = get_font(size)
        lines = wrap_text(draw, texto, font, aw)
        # también verificar que ninguna línea sea más ancha que el área
        if any(draw.textbbox((0, 0), l, font=font)[2] > aw for l in lines):
            continue
        total_h = len(lines) * size + (len(lines) - 1) * size * 0.2
        if total_h <= ah and len(lines) <= 8:
            best_size, best_lines = size, lines
            break
    if best_size is None:
        best_size = 14
        best_lines = wrap_text(draw, texto, get_font(14), aw)

    font = get_font(best_size)
    spacing = best_size * 0.2
    line_h = best_size + spacing
    total_h = len(best_lines) * best_size + (len(best_lines) - 1) * spacing
    start_y = y1 + pad_y + (ah - total_h) / 2
    stroke = max(3, int(best_size * 0.15))

    for i, line in enumerate(best_lines):
        bb = draw.textbbox((0, 0), line, font=font)
        cx = x1 + pad_x + (aw - (bb[2] - bb[0])) / 2
        draw.text((cx, start_y + i * line_h), line, font=font,
                  fill="black", stroke_width=stroke, stroke_fill="white")
    return img_pil

