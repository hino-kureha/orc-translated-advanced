def borrar_texto(img, x1, y1, x2, y2):
    rec = img[y1:y2, x1:x2].copy()
    gris = cv2.cvtColor(rec, cv2.COLOR_BGR2GRAY)
    _, mask = cv2.threshold(gris, 180, 255, cv2.THRESH_BINARY_INV)
    mask = cv2.dilate(mask, np.ones((5, 5), np.uint8), iterations=3)
    img[y1:y2, x1:x2] = cv2.inpaint(rec, mask, 9, cv2.INPAINT_TELEA)
    return img

