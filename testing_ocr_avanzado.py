def construir_system():
    glos = ""
    if GLOSARIO:
        glos = "\nGlosario obligatorio:\n" + "\n".join(f"- {k} = {v}" for k, v in GLOSARIO.items())
    ctx = f"\nContexto de la obra: {CONTEXTO_OBRA}" if CONTEXTO_OBRA else ""
    return (
        f"Eres un traductor profesional de manga del japonés al {IDIOMA_DESTINO}.\n"
        "Recibirás líneas numeradas, cada una es una burbuja de diálogo en orden de lectura. "
        "El texto viene de un OCR y puede tener errores: corrígelos usando el contexto.\n"
        "Reglas:\n"
        "- Traduce el SENTIDO natural y coloquial, no palabra por palabra.\n"
        "- Mantén el tono del personaje (formal, rudo, infantil, etc.) y las emociones.\n"
        "- Usa el contexto de las burbujas vecinas para sujetos omitidos y referencias.\n"
        "- Respuestas cortas: cada burbuja es pequeña, sé conciso.\n"
        "- Las onomatopeyas tradúcelas a un equivalente corto en español (ej: ドン = ¡Pum!).\n"
        "- Si una burbuja tiene varias frases entre 「」, son HABLANTES DISTINTOS: tradúcelas separadas con ' / '.\n"
        "- Traduce los modismos por su sentido, nunca literal (ej: 条件を飲む = aceptar una condición; "
        "千人近く = casi mil, no 'más de mil').\n"
        "- Mantén los honoríficos y apellidos como romaji (ej: 草司様 = señor Souji). "
        "NUNCA inventes ni cambies un nombre; si el OCR lo escribe distinto en varias líneas, "
        "es la misma persona: usa un solo nombre.\n"
        "- Usa los mismos términos en toda la página para el mismo concepto.\n"
        "- No expliques nada ni agregues notas.\n"
        "- Responde SOLO con el mismo número de líneas, con el formato exacto:\n"
        "  1: traducción\n  2: traducción"
        f"{ctx}{glos}"
    )

SYSTEM_PROMPT = construir_system()

def _generar(mensajes, max_new_tokens):
    texto = tok.apply_chat_template(mensajes, tokenize=False, add_generation_prompt=True)
    inputs = tok(texto, return_tensors="pt").to(llm.device)
    with torch.no_grad():
        out = llm.generate(**inputs, max_new_tokens=max_new_tokens,
                           do_sample=False, repetition_penalty=1.05)
    return tok.decode(out[0][inputs["input_ids"].shape[1]:], skip_special_tokens=True).strip()

def _parsear(respuesta, n):
    res = {}
    for m in re.finditer(r"^\s*(\d+)\s*[:：\.\)]\s*(.+?)\s*$", respuesta, flags=re.M):
        k = int(m.group(1))
        if 1 <= k <= n and k not in res:
            res[k] = m.group(2).strip().strip('"“”')
    return res

def corregir_ocr(textos):
    """Paso 1: corrige errores típicos de OCR (kanji parecidos, nombres) SIN traducir."""
    n = len(textos)
    system = (
        "Eres corrector de OCR de manga japonés. Recibes líneas numeradas que pueden tener errores "
        "de OCR: kanji parecidos confundidos, nombres leídos distinto en cada línea, símbolos raros. "
        "Corrige usando el contexto de todas las líneas (ej: お見占い→お見合い, 音波の決断→苦渋の決断, "
        "扱ってもらった→拾ってもらった). Un mismo nombre debe escribirse igual en todas. "
        "NO traduzcas. Si no estás seguro, deja el original. "
        "Responde SOLO con el mismo número de líneas, formato:\n1: texto\n2: texto")
    lineas = "\n".join(f"{i+1}: {t}" for i, t in enumerate(textos))
    resp = _generar([{"role": "system", "content": system},
                     {"role": "user", "content": lineas}],
                    max_new_tokens=120 * n + 100)
    ok = _parsear(resp, n)
    return [ok.get(i + 1, textos[i]) for i in range(n)]

def traducir_lote(textos, previo):
    """textos: lista JP. previo: lista de (jp, es) ya traducidos, como contexto."""
    n = len(textos)
    ctx = ""
    if previo:
        ctx = "Contexto previo (YA traducido, NO lo repitas):\n" + \
              "\n".join(f"{jp} -> {es}" for jp, es in previo[-6:]) + "\n\n"
    lineas = "\n".join(f"{i+1}: {t}" for i, t in enumerate(textos))
    user = f"{ctx}Traduce estas {n} burbujas:\n{lineas}"
    resp = _generar([{"role": "system", "content": SYSTEM_PROMPT},
                     {"role": "user", "content": user}],
                    max_new_tokens=80 * n + 100)
    trad = _parsear(resp, n)

    # Reintento individual para las que falten
    for i in range(1, n + 1):
        if i not in trad:
            r = _generar([{"role": "system", "content": SYSTEM_PROMPT},
                          {"role": "user", "content": f"Traduce esta burbuja:\n1: {textos[i-1]}"}],
                         max_new_tokens=150)
            p = _parsear(r, 1)
            trad[i] = p.get(1, r.split("\n")[0].strip())
    return [trad[i + 1] for i in range(n)]

